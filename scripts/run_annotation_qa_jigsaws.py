def video_frame_extent(spans: list[dict[str, Any]]) -> tuple[int, int]:
    return min(s["start_frame"] for s in spans), max(s["end_frame"] for s in spans)


def video_timestamp_label(spans: list[dict[str, Any]]) -> str:
    start_frame, end_frame = video_frame_extent(spans)
    return f"{frame_to_timestamp(start_frame)}-{frame_to_timestamp(end_frame)}"


