def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset-root", default=None,
                        help="Default: /mnt/sun/shared/datasets/surgical_skill/JIGSAWS/<task>")
    parser.add_argument("--system-prompt", required=True, help="Path to annotation-only system-prompt-A-D.md")
    parser.add_argument("--d-templates", default=None, help="Path to template-questions-A-D.md (default: alongside system prompt)")
    parser.add_argument("--model-id", default="Qwen/Qwen3.6-35B-A3B")
    parser.add_argument("--task", choices=sorted(TASK_LABELS), default="Suturing",
                        help="Which JIGSAWS task --dataset-root points at (selects the meta_file name and procedure_or_task label)")
    parser.add_argument("--trial-id", default="Suturing_B001")
    parser.add_argument("--trial-ids", default=None,
                        help="Comma-separated trial IDs to run in one invocation; overrides --trial-id if given")
    parser.add_argument("--gesture-id", default=None, help="Restrict to one gesture ID (default: all spans in the trial; ignored with --granularity video)")
    parser.add_argument("--max-spans", type=int, default=0,
                        help="Cap the number of gesture spans processed (0 = all). "
                             "Ignored with --granularity video, which emits one unit per trial.")
    parser.add_argument("--granularity", choices=["gesture", "video"], default="gesture",
                        help="gesture (default): one QA object per gesture span, timestamp_or_frame is a frame "
                             "range. video: one QA object per whole trial, timestamp_or_frame is a timestamp "
                             "range -- use this across many trials, since every gesture in a trial shares the "
                             "same GRS scores and per-gesture questions are near-duplicates of each other.")
    parser.add_argument("--templates", default="A3,C1,C2,C3,C6,C7,D1,D2,D3,D4,D5")
    parser.add_argument("--max-new-tokens", type=int, default=2048)
    parser.add_argument("--max-retries", type=int, default=2,
                        help="Re-request a record when the model returns malformed JSON, a "
                             "misspelled key, or the wrong question wording. These are transient "
                             "formatting glitches, not content problems. Only applies with "
                             "--backend real and --temperature > 0 (a retry at temperature 0 "
                             "reproduces the same output). Retry count is recorded per record.")
    parser.add_argument("--temperature", type=float, default=0.0,
                         help="0.0 (default) is greedy/deterministic. >0 enables sampling, trading "
                              "reproducibility for lexical variety across records that share the same "
                              "underlying scores -- recommended for real dataset-building runs.")
    parser.add_argument("--device-map", default="auto")
    parser.add_argument("--backend", choices=["real", "mock"], default="real",
                        help="mock builds watermarked placeholder records for pipeline smoke tests only")
    parser.add_argument("--inference-engine", choices=["transformers", "ollama"], default="transformers",
                        help="transformers: load --model-id directly (cluster). "
                             "ollama: call a local `ollama serve` for a quantized GGUF (consumer GPU).")
    parser.add_argument("--ollama-model", default="qwen3.6-35b-a3b",
                        help="Model name/tag as known to the local Ollama server (only used with --inference-engine ollama)")
    parser.add_argument("--ollama-host", default="http://localhost:11434")
    parser.add_argument("--ollama-num-ctx", type=int, default=8192,
                        help="Context window passed to Ollama; must fit prompt + thinking + answer or generation truncates")
    parser.add_argument("--output-dir", required=True)
    args = parser.parse_args()

    requested = [item.strip() for item in args.templates.split(",") if item.strip()]
    unsupported = [item for item in requested if item in UNSUPPORTED_TEMPLATES]
    unknown = [item for item in requested if item not in SUPPORTED_TEMPLATES and item not in UNSUPPORTED_TEMPLATES]
    if unknown:
        parser.error(f"Unknown template IDs: {unknown}")
    if unsupported:
        reasons = {item: UNSUPPORTED_TEMPLATES[item] for item in unsupported}
        parser.error(
            "These templates cannot be generated annotation-only from JIGSAWS: "
            f"{json.dumps(reasons)}"
        )
    templates = [item for item in requested if item in SUPPORTED_TEMPLATES]

    dataset_root = Path(
        args.dataset_root
        or f"/mnt/sun/shared/datasets/surgical_skill/JIGSAWS/{args.task}"
    )
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    system_prompt_path = Path(args.system_prompt)
    system_prompt = extract_system_prompt(system_prompt_path)
    d_templates_path = (
        Path(args.d_templates)
        if args.d_templates
        else system_prompt_path.parent / "template-questions-A-D.md"
    )
    d_templates = load_d_templates(d_templates_path)

    trial_ids = (
        [item.strip() for item in args.trial_ids.split(",") if item.strip()]
        if args.trial_ids
        else [args.trial_id]
    )
    procedure_or_task = TASK_LABELS[args.task]
    task_slug = args.task.lower()

    processor = model = None
    if args.backend == "real":
        if args.inference_engine == "ollama":
            verify_ollama_model(args.ollama_host, args.ollama_model)
        else:
            processor, model = load_text_model(args.model_id, args.device_map)

    output_name = "qa_records.jsonl" if args.backend == "real" else "qa_records.mock.jsonl"
    output_path = output_dir / output_name
    valid = rejected = 0
    total_units = 0
    # Each record is one independent model call with no memory of what it
    # wrote for other records -- threading recent openers per template_id
    # into later prompts gives the model the cross-record awareness a shared
    # system prompt alone cannot provide.
    recent_openers_by_template: dict[str, list[str]] = {}
    with output_path.open("w", encoding="utf-8") as handle:
        for trial_id in trial_ids:
            meta = read_meta(dataset_root, trial_id, args.task)
            spans = read_gesture_spans(dataset_root, trial_id)
            if args.gesture_id:
                spans = [span for span in spans if span["gesture_id"] == args.gesture_id]
                if not spans:
                    raise SystemExit(f"Gesture {args.gesture_id} not found for {trial_id}")
            # Capping spans only makes sense per-gesture; in video mode the whole
            # trial is one unit and truncating spans would silently shorten the
            # timestamp range the question refers to.
            if args.max_spans > 0 and args.granularity == "gesture":
                spans = spans[: args.max_spans]

            units = [("video", spans)] if args.granularity == "video" else [
                ("gesture", [span]) for span in spans
            ]

            for unit_kind, unit_spans in units:
                for template_id in templates:
                    total_units += 1
                    recent_openers = recent_openers_by_template.get(template_id, [])[-RECENT_OPENERS_TO_SHOW:]
                    if unit_kind == "video":
                        user_prompt = build_user_prompt_video(
                            template_id, meta, unit_spans, d_templates, procedure_or_task, recent_openers
                        )
                        expected_question = expected_d_question_video(template_id, unit_spans, d_templates, meta)
                    else:
                        user_prompt = build_user_prompt(
                            template_id, meta, unit_spans[0], d_templates, procedure_or_task, recent_openers
                        )
                        expected_question = expected_d_question(template_id, unit_spans[0], d_templates, meta)

                    # The model intermittently emits a malformed envelope --
                    # observed misspelling the "rationale" key as "rationate",
                    # and occasionally truncating mid-JSON -- while the QA
                    # content itself is fine. These are transient formatting
                    # glitches, so ask again rather than discarding the record.
                    # Retrying only helps when sampling is on; at temperature 0
                    # a retry reproduces the same output byte for byte.
                    attempts = 0
                    earlier_errors: list[str] = []
                    while True:
                        attempts += 1
                        if args.backend == "mock":
                            raw_output = (
                                mock_raw_output_video(template_id, unit_spans, d_templates, meta)
                                if unit_kind == "video"
                                else mock_raw_output(template_id, unit_spans[0], d_templates, meta)
                            )
                        elif args.inference_engine == "ollama":
                            raw_output = run_generation_ollama(
                                args.ollama_host, args.ollama_model, system_prompt, user_prompt,
                                args.max_new_tokens, args.ollama_num_ctx, args.temperature,
                            )
                        else:
                            raw_output = run_generation(
                                processor, model, system_prompt, user_prompt, args.max_new_tokens, args.temperature
                            )
                        qa_objects = None
                        error = None
                        try:
                            qa_objects = normalize_qa_objects(parse_json_payload(raw_output))
                            if qa_objects is None:
                                error = "schema_mismatch: expected objects with exactly question/answer/rationale"
                        except Exception as exc:  # noqa: BLE001
                            error = repr(exc)

                        if error is None and expected_question is not None:
                            if qa_objects[0]["question"] != expected_question:
                                error = "question_mismatch: D question must match template wording exactly"

                        retryable = (
                            error is not None
                            and attempts <= args.max_retries
                            and args.backend == "real"
                            and args.temperature > 0
                        )
                        if not retryable:
                            break
                        earlier_errors.append(error)
                        log(f"  retry {attempts}/{args.max_retries} after: {error}")

                    if error is None:
                        status = "valid" if args.backend == "real" else "valid_mock"
                        valid += 1
                        if args.backend == "real" and template_id in d_templates:
                            recent_openers_by_template.setdefault(template_id, []).append(
                                first_sentence(qa_objects[0]["answer"])
                            )
                    else:
                        status = "rejected"
                        rejected += 1

                    if unit_kind == "video":
                        timestamp_label = video_timestamp_label(unit_spans)
                        start_frame, end_frame = video_frame_extent(unit_spans)
                        qa_id = f"jigsaws_{task_slug}_{template_id.lower()}_{meta['trial_id']}_video_anno"
                        source_annotation = {
                            "meta_file": meta["source_file"],
                            "transcription_file": unit_spans[0]["source_file"],
                            "skill_level": meta["skill_level"],
                            "grs_total": meta["grs_total"],
                            "grs_subscores": meta["grs_subscores"],
                            "video_timestamp_span": timestamp_label,
                            "video_frame_span": f"{start_frame}-{end_frame}",
                            "fps_used_for_timestamp_conversion": JIGSAWS_FPS,
                            "gesture_count": len(unit_spans),
                        }
                        timestamp_or_frame = timestamp_label
                    else:
                        span = unit_spans[0]
                        frame_label = f"{span['start_frame']}-{span['end_frame']}"
                        qa_id = (
                            f"jigsaws_{task_slug}_{template_id.lower()}_{meta['trial_id']}_"
                            f"{span['gesture_id']}_{frame_label.replace('-', '_')}_anno"
                        )
                        source_annotation = {
                            "meta_file": meta["source_file"],
                            "transcription_file": span["source_file"],
                            "skill_level": meta["skill_level"],
                            "grs_total": meta["grs_total"],
                            "grs_subscores": meta["grs_subscores"],
                            "gesture_id": span["gesture_id"],
                            "gesture_definition": GESTURE_DEFINITIONS.get(span["gesture_id"]),
                            "gesture_frame_range": frame_label,
                        }
                        timestamp_or_frame = frame_label

                    record = {
                        "qa_id": qa_id,
                        "dataset": "JIGSAWS",
                        "procedure_or_task": procedure_or_task,
                        "generation_mode": "annotation_only",
                        "template_id": template_id,
                        "template_support": SUPPORTED_TEMPLATES[template_id],
                        "trial_id": meta["trial_id"],
                        "timestamp_or_frame": timestamp_or_frame,
                        "source_annotation": source_annotation,
                        "model": {
                            "backend": args.backend,
                            "real_model_inference": args.backend == "real",
                            "inference_engine": args.inference_engine if args.backend == "real" else None,
                            "model_id": (
                                (args.ollama_model if args.inference_engine == "ollama" else args.model_id)
                                if args.backend == "real"
                                else None
                            ),
                            "system_prompt_path": str(system_prompt_path),
                            "attempts": attempts,
                            "retried_after_errors": earlier_errors or None,
                            "prompt": user_prompt,
                            "raw_output": raw_output,
                        },
                        "qa": qa_objects,
                        "validation_status": status,
                        "validation_error": error,
                    }
                    handle.write(json.dumps(record, ensure_ascii=False) + "\n")
                    log(f"{record['qa_id']}: {status}" + (f" ({error})" if error else ""))

    summary = {
        "backend": args.backend,
        "task": args.task,
        "granularity": args.granularity,
        "trial_ids": trial_ids,
        "templates": templates,
        "units": total_units,
        "valid": valid,
        "rejected": rejected,
        "output": str(output_path),
    }
    (output_dir / "run_summary.json").write_text(
        json.dumps(summary, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
